import math
import random

# ==========================================
# 第一部分：准备数据（文字变数字）
# ==========================================
# 1. 我们的迷你词表（只有4个词）
vocab = ["好", "开心", "差", "讨厌"]

# 2. 我们的训练数据（两句话，以及它们的真实标签）
# 第一句：“好 开心” -> 真实标签是 1（正面）
# 第二句：“差 讨厌” -> 真实标签是 0（负面）
train_data = [
    (["好", "开心"], 1.0),
    (["差", "讨厌"], 0.0)
]

# ==========================================
# 第二部分：初始化模型参数（瞎猜）
# ==========================================
# 词表有 4 个词，所以 w 有 4 个
w = [random.uniform(-0.1, 0.1) for _ in range(4)]
b = 0.0
学习率 = 0.5

print("--- 开始训练模型 ---")

# ==========================================
# 第三部分：机器开始学习（循环 10 次）
# ==========================================
for epoch in range(10):
    total_loss = 0 # 记录本轮的总误差
    
    # 遍历每一句话（每次拿一句话和它的真实答案）
    for words, y_true in train_data:
        
        # 1. 提取特征 x：把这句话变成向量 [0, 1, 0, 0] 这种形式
        x = []
        for v in vocab:
            if v in words:
                x.append(1.0) # 词出现了，填 1
            else:
                x.append(0.0) # 词没出现，填 0
                
        # 2. 前向传播：算预测概率 y_hat
        z = sum(wi * xi for wi, xi in zip(w, x)) + b
        # 防爆保护
        z = max(min(z, 100), -100)
        y_hat = 1 / (1 + math.exp(-z))
        
        # 3. 算偏差（梯度方向）
        偏差 = y_hat - y_true
        total_loss += (偏差 ** 2) # 累加平方误差，方便看模型有没有变好
        
        # 4. 反向传播：更新 w 和 b
        for i in range(4):
            w[i] = w[i] - 学习率 * 偏差 * x[i]
        b = b - 学习率 * 偏差
        
    if (epoch + 1) % 2 == 0:
        print(f"第 {epoch+1} 轮学习: 总误差 = {total_loss:.4f}")

# ==========================================
# 第四部分：模型毕业了，来做推理测试（预测新句子）
# ==========================================
print("\n--- 训练结束，开始预测 ---")

# 我们输入一句没学过的话：“好 差”
test_words = ["好", "差"]
test_x = []
for v in vocab:
    if v in test_words:
        test_x.append(1.0)
    else:
        test_x.append(0.0)

z = sum(wi * xi for wi, xi in zip(w, test_x)) + b
y_hat = 1 / (1 + math.exp(-z))

print(f"测试句子: {test_words}")
print(f"这句话的向量表示: {test_x}")
print(f"模型预测它是正面情感的概率: {y_hat:.4f}")

if y_hat > 0.5:
    print("模型最终判决：正面情感 😄")
else:
    print("模型最终判决：负面情感 😡")