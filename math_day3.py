# 假设当前位置是 4
x = 4.0
learning_rate = 0.1  # 每一步走多大

print("--- 开始下山 ---")
for step in range(10):
    # 1. 算当前高度（损失 Loss）
    y = x * x
    print(f"第 {step+1} 步: 当前位置 x={x:.2f}, 当前高度 y={y:.2f}")
    
    # 2. 算斜率（导数）。对于 y = x^2，它的导数公式是 2*x
    # （这是数学家推导出来的，你只需要知道：斜率 = 2 * x）
    slope = 2 * x
    
    # 3. 开始下山：往斜率相反的方向走（斜率为正就往下走，斜率为负就往上走）
    # x 减去 斜率 * 学习率
    x = x - learning_rate * slope

print(f"\n最终停在 x={x:.2f}，此时高度最低（接近0）！")