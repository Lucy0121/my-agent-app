import math

y_true = 1.0 # 真实目标：正面情感
b = -2.0 # 机器一开始很笨，b 默认是 -2.0
学习率 = 0.5

for i in range(5):
    # 1. 机器给出目前的预测概率（Sigmoid公式，你之前见过的）
    y_hat = 1 / (1+math.exp(-b))

    # 2. 看看猜得有多离谱（预测值 - 真实值）
    偏差 = y_hat - y_true

    # 3. 根据偏差，调整 b 的大小（更新参数）
    b = b - 学习率 * 偏差

    print(f"第{i+1}次：机器预测概率是 {y_hat:.3f}， 偏差是 {偏差:.3f}，调整后的 b 是 {b:.3f}")