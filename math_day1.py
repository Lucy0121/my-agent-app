import numpy as np

# 1. 向量（Vector）
v1 = np.array([1, 2, 3])
v2 = np.array([4, 5, 6])

# 【数学公式】点积 = 1*4 + 2*5 + 3*6 = 4 + 10 + 18 = 32
# 【代码实现】
dot_product = np.dot(v1, v2) 
print("向量的点积结果:", dot_product) # 输出 32

# 2. 矩阵（Matrix）
# 我们造一个 2x3 的矩阵 A，和一个 3x2 的矩阵 B
# 根据规则：中间维度 3 和 3 必须相等，结果应该是 2x2
A = np.array([[1, 2, 3], 
              [4, 5, 6]])

B = np.array([[7, 8], 
              [9, 10], 
              [11, 12]])

# 【代码实现】矩阵乘法
C = A @ B
print("矩阵乘法结果:\n", C)

# 我们来手算验证 C 的第一行第一列：
# A的第一行 [1, 2, 3] 点乘 B的第一列 [7, 9, 11]
# 1*7 + 2*9 + 3*11 = 7 + 18 + 33 = 58
print("手算验证第一行第一列:", 1*7 + 2*9 + 3*11)