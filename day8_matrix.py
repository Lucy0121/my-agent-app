import numpy as np
import time

# ==========================================
# 1. 准备数据：用 NumPy 创建“表格”（矩阵）
# ==========================================
# 假设我们有 10 万句话（行），每句话有 100 个词的特征（列）
# 在 NumPy 里，np.ones 可以瞬间造出一个全是 1 的大表格
X = np.ones((100000, 100)) 
W = np.ones(100) * 0.5  # 模型有 100 个权重

# ==========================================
# 2. 老方法：用 for 循环硬算 (跑一次)
# ==========================================
start_time = time.time()
Z_old = []
for i in range(100000):
    # 每一句话，跟权重做乘积累加
    z = sum(W[j] * X[i][j] for j in range(100))
    Z_old.append(z)
old_time = time.time() - start_time
print(f"老方法 (for 循环) 耗时: {old_time:.4f} 秒")

# ==========================================
# 3. 矩阵魔法：一行代码算完 (跑一次)
# ==========================================
start_time = time.time()
# 注意看！这里没有 for 循环！
# 直接用 X 和 W 做矩阵乘法（@ 符号代表矩阵乘法）
Z_new = X @ W 
new_time = time.time() - start_time
print(f"矩阵魔法 (NumPy) 耗时: {new_time:.6f} 秒")

# 看看结果是不是一样的
print("\n老方法算出的第一句话得分:", Z_old[0])
print("矩阵魔法算出的第一句话得分:", Z_new[0])